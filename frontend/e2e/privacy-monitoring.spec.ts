test('admin grants another registered account access by email and its existing session gains staff access', async ({ page, browser }) => {
  const email = `new-admin-${Date.now()}@example.com`
  expect((await page.request.post('/auth/register', { data: { name: 'New admin E2E', email, password } })).status()).toBe(201)
  const second = await browser.newContext()
  try {
    const traveler = await second.newPage()
    await traveler.goto('/sign-in')
    await traveler.getByLabel('Email', { exact: true }).fill(email)
    await traveler.getByLabel('Password', { exact: true }).fill(password)
    await traveler.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(traveler.getByRole('link', { name: 'Your applications', exact: true })).toHaveAttribute('href', '/apply')
    await traveler.getByRole('link', { name: 'Staff dashboard', exact: true }).click()
    await expect(traveler.getByRole('alert')).toContainText('active admin')
    await page.goto('/sign-in')
    await page.getByLabel('Email', { exact: true }).fill('qa-admin@example.com')
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Welcome, Demo Admin', exact: true })).toBeVisible()
    await page.goto('/admin')
    await page.getByLabel('New admin email').fill(email.toUpperCase())
    await page.getByRole('button', { name: 'Find account', exact: true }).click()
    await expect(page.getByRole('button', { name: `Confirm admin access for ${email}` })).toBeVisible()
    await page.getByRole('button', { name: `Confirm admin access for ${email}` }).click()
    await expect(page.getByText('New admin E2E is now an admin.', { exact: true })).toBeVisible()
    await traveler.goto('/backoffice')
    await expect(traveler.getByRole('heading', { name: 'Applications by status' })).toBeVisible()
    await traveler.goto('/admin')
    await expect(traveler.getByRole('heading', { name: 'Add an admin', exact: true })).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  } finally { await second.close() }
})
