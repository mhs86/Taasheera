import { expect, test } from '@playwright/test'

const password = 'Local-preview-only-123!'

test('traveler creates a draft, sees passport access, restores session and deletes all data', async ({ page, context }) => {
  const unique = `e2e-${Date.now()}@example.com`
  // Synthetic registration goes through the real backend, then the real browser signs in.
  const registered = await page.request.post('/auth/register', { data: { name: 'E2E Synthetic', email: unique, password } })
  expect(registered.status()).toBe(201)
  await page.goto('/sign-in')
  await page.getByLabel('Email', { exact: true }).fill(unique)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome, E2E Synthetic' })).toBeVisible()
  const cookies = await context.cookies()
  const refreshCookie = cookies.find(cookie => cookie.name === 'taasheera_refresh')
  expect(refreshCookie?.httpOnly).toBe(true)
  expect(refreshCookie?.sameSite).toBe('Strict')
  expect(refreshCookie?.path).toBe('/auth')
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Welcome, E2E Synthetic' })).toBeVisible()
  await page.getByRole('link', { name: 'Your applications', exact: true }).click()
  await page.getByLabel('Destination', { exact: true }).selectOption('FRA')
  await page.getByLabel('Passport nationality').selectOption('LBN')
  await page.getByLabel('Visa type').fill('Synthetic tourist')
  await page.getByRole('button', { name: 'Start application', exact: true }).click()
  await expect(page.locator('li').filter({ hasText: 'Synthetic tourist' })).toContainText('DRAFT')
  await page.goto('/backoffice')
  await expect(page.getByRole('alert')).toContainText('active admin')

  await page.goto('/passport')
  // Use a generated specimen-size canvas rather than any real passport.
  const bytes = await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 400; canvas.height = 300
    const ctx = canvas.getContext('2d')!; ctx.fillStyle = 'white'; ctx.fillRect(0, 0, 400, 300)
    ctx.fillStyle = 'black'; ctx.font = '20px sans-serif'; ctx.fillText('SPECIMEN TEST ONLY', 35, 150)
    return Array.from(new Uint8Array(await (await new Promise<Blob>(resolve => canvas.toBlob(value => resolve(value!), 'image/jpeg'))).arrayBuffer()))
  })
  await page.locator('input[type="file"]').first().setInputFiles({ name: 'synthetic.jpg', mimeType: 'image/jpeg', buffer: Buffer.from(bytes) })
  await expect(page).toHaveURL(/\/passport\/[a-f0-9]{32}/)
  await expect(page.getByRole('img', { name: /passport/i })).toBeVisible()
  await page.goto('/account')
  await page.getByRole('button', { name: 'Refresh access history' }).click()
  await expect(page.locator('.access-history')).toContainText('You')
  await expect(page.locator('.access-history')).toContainText('Viewed passport image')
  await page.getByRole('button', { name: 'Delete my account', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Permanently delete account', exact: true })).toBeDisabled()
  await page.getByLabel('Current password', { exact: true }).last().fill(password)
  await page.getByLabel('Type DELETE to confirm permanent deletion').fill('DELETE')
  await page.getByRole('button', { name: 'Permanently delete account', exact: true }).click()
  await expect(page.getByText('Your account and data have been deleted.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Welcome back', exact: true })).toBeVisible()
  expect((await context.cookies()).some(cookie => cookie.name === 'taasheera_refresh')).toBe(false)
})

test('admin dashboard displays persisted counts and deletes a selected synthetic user', async ({ page }) => {
  await page.goto('/sign-in')
  await page.getByLabel('Email', { exact: true }).fill('qa-admin@example.com')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Welcome/ })).toBeVisible()
  const unique = `e2e-delete-${Date.now()}@example.com`
  expect((await page.request.post('/auth/register', { data: { name: 'Disposable E2E', email: unique, password } })).status()).toBe(201)
  await page.getByRole('link', { name: 'Staff dashboard' }).click()
  await expect(page.getByRole('heading', { name: 'Applications by status' })).toBeVisible()
  await expect(page.locator('.status-card')).toHaveCount(6)
  await expect(page.getByRole('heading', { name: 'Recent errors' })).toBeVisible()
  await page.getByLabel('Search name or email').fill(unique)
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('cell', { name: unique })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Disposable E2E', exact: true }).click()
  await page.getByLabel('Type DELETE to confirm', { exact: true }).fill('DELETE')
  await page.getByRole('button', { name: 'Confirm permanent deletion' }).click()
  await expect(page.getByText('User and associated data deleted.', { exact: true })).toBeVisible()
  await expect(page.getByText('No users match your search.', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
